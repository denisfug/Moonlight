#!/usr/bin/env python3
"""Generates src/net/ca_roots.inc: the trust anchors of the app's own TLS client (src/net/tls.cpp).

Union of
  1. the Mozilla trust store of the build machine (ca-certificates, MPL-2.0), and
  2. tools/certifi-2024.8.30-cacert.pem (the same Mozilla store as published by certifi 2024.8.30, MPL-2.0),
minus certificates already expired. Why both: Mozilla has since removed older roots (GlobalSign Root CA,
DigiCert Global Root CA, AAA Certificate Services, Go Daddy, Starfield...) that many servers still chain
to; with only the current store the console reported "emissor do certificado desconhecido" (01.12).

usage: tools/make_ca_roots.py [current.pem] [older.pem]"""
import datetime, pathlib, re, subprocess, sys

here = pathlib.Path(__file__).resolve().parent
cur = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs/ca-certificates.crt"
old = sys.argv[2] if len(sys.argv) > 2 else str(here / "certifi-2024.8.30-cacert.pem")

def pems(path):
    return [p.strip() + "\n" for p in re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pathlib.Path(path).read_text(), re.S)]

def info(pem):
    out = subprocess.run(["openssl", "x509", "-noout", "-subject", "-enddate", "-fingerprint", "-sha256", "-nameopt", "oneline"],
                         input=pem, capture_output=True, text=True).stdout
    subj = re.search(r"subject=(.*)", out).group(1).strip()
    end = re.search(r"notAfter=(.*)", out).group(1).strip()
    fp = re.search(r"Fingerprint=(.*)", out).group(1).strip()
    exp = datetime.datetime.strptime(end.replace(" GMT", ""), "%b %d %H:%M:%S %Y")
    cn = re.search(r"CN = ([^,]+)", subj)
    ou = re.search(r"OU = ([^,]+)", subj)
    return (cn.group(1) if cn else ou.group(1) if ou else subj), exp, fp

seen, out, expired = set(), [], 0
now = datetime.datetime.utcnow()
for src in (cur, old):
    for p in pems(src):
        name, exp, fp = info(p)
        if fp in seen: continue
        seen.add(fp)
        if exp < now: expired += 1; continue
        out.append((name, p))
lines = [f"// Generated by tools/make_ca_roots.py from {pathlib.Path(cur).name} + {pathlib.Path(old).name} (Mozilla trust store, MPL-2.0). Do not edit.",
         f"#define ML_CA_ROOT_COUNT {len(out)}"]
for i, (name, p) in enumerate(out):
    lines.append(f"// {name}")
    lines.append(f"static const char kCaRoot{i}[] =")
    lines += ['    "' + l + '\\n"' for l in p.strip().split("\n")]
    lines[-1] += ";"
lines.append("static const char *const kCaRoots[ML_CA_ROOT_COUNT] = {" + ", ".join(f"kCaRoot{i}" for i in range(len(out))) + "};")
lines.append("static const unsigned kCaRootSizes[ML_CA_ROOT_COUNT] = {" + ", ".join(f"sizeof kCaRoot{i} - 1" for i in range(len(out))) + "};")
dst = here.parent / "src/net/ca_roots.inc"
dst.write_text("\n".join(lines) + "\n")
print(f"{dst}: {len(out)} roots ({expired} expired skipped)")
