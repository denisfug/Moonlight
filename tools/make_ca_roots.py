#!/usr/bin/env python3
"""Generates src/platform/ps4/network/ca_roots.inc: a curated set of current root CAs (PEM) taken from the
Mozilla trust store shipped by the build machine (ca-certificates, MPL-2.0). Old PS4 firmware carries an
outdated root list, so modern sites fail certificate verification (sceHttpSendRequest 0x8095F00C).
The roots are added to the HTTP context with sceHttpsLoadCert; verification stays ON.

usage: tools/make_ca_roots.py [/etc/ssl/certs/ca-certificates.crt]"""
import re, subprocess, sys, pathlib

# Order: RSA first, so a firmware that rejects ECC keys can be retried with the first RSA_COUNT entries.
RSA = [
    "ISRG Root X1",                         # Let's Encrypt
    "DigiCert Global Root G2",
    "DigiCert Trusted Root G4", "DigiCert TLS RSA4096 Root G5",
    "GTS Root R1",                          # Google Trust Services (also Cloudflare)
    "GlobalSign",                           # R3 and R6 share this CN
    "GlobalSign Root R46",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root R46",
    "Amazon Root CA 1", "Amazon Root CA 2",
    "Microsoft RSA Root Certificate Authority 2017",
    "Certum Trusted Network CA",
]
ECC = [
    "ISRG Root X2",
    "DigiCert Global Root G3",
    "GTS Root R3", "GTS Root R4",
    "GlobalSign Root E46", "DigiCert TLS ECC P384 Root G5",
    "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Amazon Root CA 3", "Amazon Root CA 4",
    "Microsoft ECC Root Certificate Authority 2017",
]

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs/ca-certificates.crt"
    text = pathlib.Path(src).read_text()
    pems = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----\n", text, re.S)
    by_cn = {}  # CN -> [pem, ...] (several roots can share a CN)
    for p in pems:
        subj = subprocess.run(["openssl", "x509", "-noout", "-subject", "-nameopt", "multiline"],
                              input=p, capture_output=True, text=True).stdout
        m = re.search(r"commonName\s*=\s*(.+)", subj)
        if m:
            by_cn.setdefault(m.group(1).strip(), []).append(p)
    out, missing = [], []
    for cn in RSA + ECC:
        if cn in by_cn:
            for pem in by_cn[cn]:
                key = subprocess.run(["openssl", "x509", "-noout", "-text"], input=pem, capture_output=True, text=True).stdout
                rsa = "rsaEncryption" in key
                if rsa != (cn in RSA):
                    print("skip (unexpected key type):", cn, file=sys.stderr)
                    continue
                out.append((cn, pem, rsa))
        else:
            missing.append(cn)
    if missing:
        print("missing:", ", ".join(missing), file=sys.stderr)
    nrsa = sum(1 for _, _, r in out if r)
    lines = ["// Generated by tools/make_ca_roots.py from " + src + " (Mozilla trust store, MPL-2.0). Do not edit.",
             f"#define ML_CA_ROOT_COUNT {len(out)}", f"#define ML_CA_ROOT_RSA_COUNT {nrsa}",
             "static const char *const kCaRootNames[ML_CA_ROOT_COUNT] = {"]
    lines += [f'    "{cn}",' for cn, _, _ in out] + ["};"]
    for i, (cn, p, _) in enumerate(out):
        lines.append(f"static const char kCaRoot{i}[] =")
        lines += ['    "' + l + '\\n"' for l in p.strip().split("\n")]
        lines[-1] += ";"
    lines.append("static const char *const kCaRoots[ML_CA_ROOT_COUNT] = {" + ", ".join(f"kCaRoot{i}" for i in range(len(out))) + "};")
    lines.append("static const unsigned kCaRootSizes[ML_CA_ROOT_COUNT] = {" + ", ".join(f"sizeof kCaRoot{i} - 1" for i in range(len(out))) + "};")
    dst = pathlib.Path(__file__).resolve().parent.parent / "src/platform/ps4/network/ca_roots.inc"
    dst.write_text("\n".join(lines) + "\n")
    print(f"{dst}: {len(out)} roots ({nrsa} RSA)")

main()
